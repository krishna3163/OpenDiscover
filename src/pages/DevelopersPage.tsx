import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { useToast } from '../context/toast';
import { STAFF_ROSTER } from '../config/demo';
import { CATALOGUE_STATS } from '../lib/catalog';
import { CONTRIBUTING_URL, ISSUE_URL, REPO_URL, SECURITY_URL } from '../lib/routes';

const SNIPPETS = [
  {
    label: 'Fetch the whole catalogue',
    code: `curl -s ${'{SITE}'}/data/projects.json | jq '.projects[0]'`,
  },
  {
    label: 'Shareable search URL (the UI’s own query API)',
    code: `/?q=privacy+browser&sort=trust&license=GPL-3.0&platform=Android&verified=1`,
  },
  {
    label: 'Filter the JSON for open-licence Android apps',
    code: `jq '.projects[] | select(.licenseKind=="permissive") | select(.platforms|index("Android")) | .title' projects.json`,
  },
];

/**
 * Developer hub: who maintains this, how to get listed, and how to consume the
 * data. The JSON endpoint is real (generated by `npm run export:data`); there
 * is no authenticated REST API yet, and the page says so.
 */
export const DevelopersPage: React.FC = () => {
  const toast = useToast();
  const [copied, setCopied] = useState<string | null>(null);

  /** Absolute origin this deployment is served from (works on Pages too). */
  const siteOrigin = `${window.location.origin}${import.meta.env.BASE_URL}`.replace(/\/+$/, '');
  const resolve = (code: string) => code.replace('{SITE}', siteOrigin);

  const copy = async (label: string, text: string) => {
    const value = resolve(text);
    try {
      await navigator.clipboard.writeText(value);
      setCopied(label);
      toast.success('Copied to clipboard');
      window.setTimeout(() => setCopied(null), 2000);
    } catch {
      toast.error('Clipboard blocked', 'Select the snippet and copy manually.');
    }
  };

  return (
    <div className="container section">
      <header className="section-head">
        <h1>For developers</h1>
        <p>
          OpenDiscover is MIT-licensed and open for contributions — {CATALOGUE_STATS.projects} listings,{' '}
          {CATALOGUE_STATS.licenses} distinct licences, one TypeScript source of truth.
        </p>
      </header>

      <section className="detail-block" aria-labelledby="team-heading">
        <h2 id="team-heading" className="section-title">
          Meet the team
        </h2>
        <div className="team-grid">
          {STAFF_ROSTER.filter((member) => member.name !== 'Bot').map((member) => (
            <div key={member.handle} className={`card team-card${member.name === 'Krishna' ? ' team-card-lead' : ''}`}>
              <span className="team-avatar" aria-hidden="true">
                {member.name.charAt(0)}
              </span>
              <h3>{member.name}</h3>
              <p>{member.role}</p>
              {member.name === 'Krishna' && <Link to="/profile">View profile →</Link>}
            </div>
          ))}
        </div>
      </section>

      <section className="card detail-block" aria-labelledby="api-heading">
        <h2 id="api-heading" className="section-title">
          Data &amp; endpoints
        </h2>
        <p>
          The build exports the full catalogue to <code>/data/projects.json</code> — no key, no auth, no rate limit.
          Deep links into the UI accept the same query parameters the explorer writes, so any filtered result set is a
          stable URL you can embed.
        </p>

        <div className="snippet-list">
          {SNIPPETS.map((snippet) => (
            <figure key={snippet.label} className="snippet">
              <figcaption>
                {snippet.label}
                <button type="button" className="btn btn-ghost btn-sm" onClick={() => copy(snippet.label, snippet.code)}>
                  {copied === snippet.label ? '✓ Copied' : 'Copy'}
                </button>
              </figcaption>
              <pre>
                <code>{resolve(snippet.code)}</code>
              </pre>
            </figure>
          ))}
        </div>

        <p className="notice">
          A hosted REST API (<code>api.opendiscover.dev</code>) does not exist yet — the snippets above describe what
          this deployment actually serves. Want it?{' '}
          <a href={ISSUE_URL} target="_blank" rel="noopener noreferrer">
            Open an issue
          </a>
          .
        </p>
      </section>

      <section className="card detail-block" aria-labelledby="submit-heading">
        <h2 id="submit-heading" className="section-title">
          Listing criteria
        </h2>
        <ul className="check-list">
          <li>OSI-approved licence (MIT, Apache, GPL, MPL…) or a documented model licence for weights.</li>
          <li>Publicly accessible source repository — GitHub, GitLab, Codeberg, Hugging Face.</li>
          <li>Active maintenance: a commit or release within the last 12 months is preferred.</li>
          <li>Official upstream link only. No mirrors, repackaged binaries or download portals.</li>
          <li>Honest Trust Score based on the published rubric.</li>
        </ul>
        <div className="btn-row">
          <Link to="/submit" className="btn btn-primary">
            Submit a project
          </Link>
          <a href={CONTRIBUTING_URL} className="btn btn-outline" target="_blank" rel="noopener noreferrer">
            Contributing guide
          </a>
          <a href={SECURITY_URL} className="btn btn-outline" target="_blank" rel="noopener noreferrer">
            Security policy
          </a>
          <a href={REPO_URL} className="btn btn-ghost" target="_blank" rel="noopener noreferrer">
            ★ Star on GitHub
          </a>
        </div>
      </section>

      <section className="card detail-block" aria-labelledby="stack-heading">
        <h2 id="stack-heading" className="section-title">
          How it is built
        </h2>
        <dl className="stat-list stat-list-wide">
          <div>
            <dt>Frontend</dt>
            <dd>React 19 + TypeScript (strict)</dd>
          </div>
          <div>
            <dt>Bundler</dt>
            <dd>Vite 7, code-split per route</dd>
          </div>
          <div>
            <dt>Routing</dt>
            <dd>React Router 7 (URL-driven search state)</dd>
          </div>
          <div>
            <dt>Motion</dt>
            <dd>Framer Motion, reduced-motion aware</dd>
          </div>
          <div>
            <dt>Styling</dt>
            <dd>Vanilla CSS custom properties — no UI framework</dd>
          </div>
          <div>
            <dt>Quality</dt>
            <dd>ESLint 9 + tsc + Vitest in GitHub Actions</dd>
          </div>
          <div>
            <dt>AI assistant</dt>
            <dd>Gemini via REST, proxy-ready, offline fallback</dd>
          </div>
          <div>
            <dt>Hosting</dt>
            <dd>GitHub Pages / any static host</dd>
          </div>
        </dl>
      </section>
    </div>
  );
};

export default DevelopersPage;
